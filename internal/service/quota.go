func PostConsumeQuota(relayInfo *relaycommon.RelayInfo, quota billing.MicroUSD, preConsumedQuota billing.MicroUSD, sendEmail bool) (err error) {
	return postConsumeQuota(relayInfo, quota, preConsumedQuota, sendEmail, true)
}

func postConsumeQuota(relayInfo *relaycommon.RelayInfo, quota billing.MicroUSD, preConsumedQuota billing.MicroUSD, sendEmail bool, recordFailure bool) (err error) {
	if model.GatewayLedgerEnabled() {
		return settleRedisLedger(relayInfo, quota+preConsumedQuota, false)
	}
	relayInfo.SettledChargeMicrousd = preConsumedQuota
	if relayInfo.BudgetSettlementAt.IsZero() {
		relayInfo.BudgetSettlementAt = time.Now().UTC()
	}
	if quota == 0 {
		if sendEmail && preConsumedQuota != 0 {
			checkAndSendQuotaNotify(relayInfo, quota, preConsumedQuota)
		}
		if relayInfo.ProjectID > 0 {
			err = model.FinalizeProjectSpendBudget(spendBudgetChargeInputFromRelay(relayInfo, preConsumedQuota))
			if err != nil && recordFailure {
				refID, metadata := relayQuotaLedgerEventData(relayInfo, "relay_settlement", preConsumedQuota)
				recordSettlementFailure(relayInfo, quota, preConsumedQuota, refID, metadata, err)
			}
			if err == nil && sendEmail && preConsumedQuota != 0 {
				checkAndSendTokenUsageAlert(relayInfo)
			}
			return err
		}
		recordSpendBudgetCharge(relayInfo, preConsumedQuota)
		releaseSpendBudgetReservationForRelay(relayInfo)
		return nil
	}
	refID, metadata := relayQuotaLedgerEventData(relayInfo, "relay_settlement", preConsumedQuota)
	var outbox *model.SettlementOutbox
	if common.SettlementOutboxEnabled && recordFailure && quota != 0 {
		outbox, err = recordSettlementOutbox(relayInfo, quota, preConsumedQuota, refID, metadata)
		if err != nil {
			return err
		}
	}
	if outbox != nil {
		relayInfo.SettledChargeMicrousd = quota + preConsumedQuota
	}
	timer := common.StartHotPathStage(common.HotPathStageSettlementPost)
	err = model.AdjustRelayQuotaWithLedger(model.AdjustRelayQuotaWithLedgerInput{
		AcceptedSettlement: true,
		UserID:             relayInfo.BillingUserID(),
		TokenID:            relayInfo.TokenId,
		TokenKey:           relayInfo.TokenKey,
		TokenUnlimited:     relayInfo.TokenUnlimited,
		IsPlayground:       relayInfo.IsPlayground,
		QuotaDelta:         quota,
		RefType:            "relay_settlement",
		RefID:              refID,
		PricingVersion:     relayInfo.PriceData.PricingVersion,
		Metadata:           metadata,
	})
	timer.Finish(err)
	if err != nil {
		if recordFailure {
			recordSettlementFailure(relayInfo, quota, preConsumedQuota, refID, metadata, err)
		}
		return err
	}
	relayInfo.SettledChargeMicrousd = quota + preConsumedQuota
	if relayInfo.ProjectID > 0 {
		if budgetErr := model.FinalizeProjectSpendBudget(spendBudgetChargeInputFromRelay(relayInfo, quota+preConsumedQuota)); budgetErr != nil {
			if recordFailure {
				recordSettlementFailure(relayInfo, quota, preConsumedQuota, refID, metadata, budgetErr)
			}
			return budgetErr
		}
	}
	if outbox != nil {
		if resolveErr := model.ResolveSettlementOutbox(outbox.ID, time.Now().UTC()); resolveErr != nil {
			common.SysLog("failed to resolve settlement outbox after successful settlement: " + resolveErr.Error())
		}
	}

	if sendEmail {
		if (quota + preConsumedQuota) != 0 {
			checkAndSendQuotaNotify(relayInfo, quota, preConsumedQuota)
			checkAndSendTokenUsageAlert(relayInfo)
		}
	}
	recordSpendBudgetCharge(relayInfo, quota+preConsumedQuota)
	releaseSpendBudgetReservationForRelay(relayInfo)

	return nil
}

func recordSettlementOutbox(relayInfo *relaycommon.RelayInfo, quota billing.MicroUSD, preConsumedQuota billing.MicroUSD, refID string, metadata map[string]any) (*model.SettlementOutbox, error) {
	if relayInfo == nil || quota == 0 {
		return nil, nil
	}
	row := model.SettlementOutbox{
		ProjectID: relayInfo.ProjectID, ActorUserID: relayInfo.ActorID(),
		RequestID:      relayInfo.RequestID,
		UserID:         relayInfo.BillingUserID(),
		TokenID:        relayInfo.TokenId,
		TokenKey:       relayInfo.TokenKey,
		TokenUnlimited: relayInfo.TokenUnlimited,
		IsPlayground:   relayInfo.IsPlayground,
		QuotaDelta:     quota,
		PreConsumed:    preConsumedQuota,
		RefType:        "relay_settlement",
		RefID:          refID,
		PricingVersion: relayInfo.PriceData.PricingVersion,
		Status:         model.SettlementFailureStatusOpen,
		Metadata:       common.MapToJsonStr(metadata),
	}
	return model.RecordSettlementOutbox(row)
}

func recordSettlementFailure(relayInfo *relaycommon.RelayInfo, quota billing.MicroUSD, preConsumedQuota billing.MicroUSD, refID string, metadata map[string]any, settleErr error) {
	if relayInfo == nil || settleErr == nil {
		return
	}
	row := model.SettlementFailure{
		ProjectID: relayInfo.ProjectID, ActorUserID: relayInfo.ActorID(),
		RequestID:      relayInfo.RequestID,
		UserID:         relayInfo.BillingUserID(),
		TokenID:        relayInfo.TokenId,
		TokenKey:       relayInfo.TokenKey,
		TokenUnlimited: relayInfo.TokenUnlimited,
		IsPlayground:   relayInfo.IsPlayground,
		QuotaDelta:     quota,
		PreConsumed:    preConsumedQuota,
		RefType:        "relay_settlement",
		RefID:          refID,
		PricingVersion: relayInfo.PriceData.PricingVersion,
		Error:          settleErr.Error(),
		Status:         model.SettlementFailureStatusOpen,
		Metadata:       common.MapToJsonStr(metadata),
	}
	if err := model.RecordSettlementFailure(row); err != nil {
		common.SysLog("failed to persist settlement failure after settlement error: " + err.Error())
	}
}

func relayQuotaLedgerEventData(relayInfo *relaycommon.RelayInfo, refType string, preConsumedQuota billing.MicroUSD) (string, map[string]any) {
	refID := fmt.Sprintf("%s:%d:%d:%d", refType, relayInfo.BillingUserID(), relayInfo.TokenId, time.Now().UnixNano())
	channelID := 0
	if relayInfo.ChannelMeta != nil {
		channelID = relayInfo.ChannelId
	}
	return refID, map[string]any{
		"project_id": relayInfo.ProjectID, "payer_user_id": relayInfo.BillingUserID(), "actor_user_id": relayInfo.ActorID(),
		"budget_occurred_at": relayInfo.BudgetSettlementAt,
		"pre_consumed_quota": preConsumedQuota.Int64(),
		"pricing_version":    relayInfo.PriceData.PricingVersion,
		"token_id":           relayInfo.TokenId,
		"token_key":          relayInfo.TokenKey,
		"token_unlimited":    relayInfo.TokenUnlimited,
		"is_playground":      relayInfo.IsPlayground,
		"channel_id":         channelID,
		"model":              relayInfo.OriginModelName,
		"group":              relayInfo.UsingGroup,
		"session_id":         relayInfo.SessionID,
		"agent_id":           relayInfo.AgentID,
	}
}

func spendBudgetChargeInputFromRelay(relayInfo *relaycommon.RelayInfo, delta billing.MicroUSD) model.SpendBudgetChargeInput {
	if relayInfo == nil {
		return model.SpendBudgetChargeInput{DeltaMicrousd: delta, OccurredAt: time.Now().UTC()}
	}
	return model.SpendBudgetChargeInput{
		ProjectID: relayInfo.ProjectID, PayerUserID: relayInfo.BillingUserID(), ActorUserID: relayInfo.ActorID(),
		UserID:        relayInfo.BillingUserID(),
		TokenID:       relayInfo.TokenId,
		SessionID:     relayInfo.SessionID,
		AgentID:       relayInfo.AgentID,
		RequestID:     relayInfo.RequestID,
		DeltaMicrousd: delta,
		OccurredAt:    relayInfo.BudgetSettlementAt,
	}
}

func recordSpendBudgetCharge(relayInfo *relaycommon.RelayInfo, delta billing.MicroUSD) {
	if relayInfo == nil || delta <= 0 {
		return
	}
	if err := model.RecordSpendBudgetCharge(spendBudgetChargeInputFromRelay(relayInfo, delta)); err != nil {
		common.SysLog("failed to record spend budget alert: " + err.Error())
	}
}

func checkAndSendQuotaNotify(relayInfo *relaycommon.RelayInfo, quota billing.MicroUSD, preConsumedQuota billing.MicroUSD) {
	common.SafeGo("quota-low-balance-notify", func() {
		userSetting, userEmail, err := quotaNotifyRecipient(relayInfo)
		if err != nil {
			common.SysError("failed to load project payer notification settings: " + err.Error())
			return
		}
		// One platform threshold decides when a balance counts as low. It used
		// to be two options holding the same number — QuotaRemindThreshold and
		// the email setting — where the email one silently won whenever low
		// balance mail was on, so the value an operator edited was usually not
		// the value the gateway read. The email setting is now the only one,
		// and LowBalanceEnabled governs the dedicated mail alone; a user's own
		// webhook or Bark notification still fires on this threshold.
		threshold := billing.USD(email_setting.GetEmailSetting().LowBalanceThresholdUSD)
		if userSetting.QuotaWarningThreshold != 0 {
			threshold = billing.MicroUSD(userSetting.QuotaWarningThreshold)
		}

		//noMoreQuota := userCache.Quota-(quota+preConsumedQuota) <= 0
		quotaTooLow := false
		consumeQuota := quota + preConsumedQuota
		remaining := relayInfo.UserQuota - consumeQuota
		if remaining < threshold {
			quotaTooLow = true
		}
		if !quotaTooLow {
			return
		}
		// Mail has one voice for a low balance: the dedicated low-balance mail,
		// governed by the platform switch and its reminder schedule. The older
		// generic notice now only reaches a user's own webhook, Bark or Gotify.
		if email_setting.GetEmailSetting().LowBalanceEnabled {
			user, err := model.GetUserById(relayInfo.BillingUserID(), true)
			if err != nil {
				common.SysError(fmt.Sprintf("failed to load user for low balance email: %v", err))
			} else {
				_, _ = SendLowBalanceEmailIfNeeded(user, remaining, threshold)
			}
		}

		notifyType := userSetting.NotifyType
		if notifyType == "" || notifyType == dto.NotifyTypeEmail {
			return
		}
		prompt := "您的额度即将用尽"
		link := common.MailSiteURL(model.UserSurfacePath(model.GetUserHomeSurface(relayInfo.BillingUserID()), model.SurfaceLinkWallet))
		var content string
		var values []interface{}
		if notifyType == dto.NotifyTypeBark {
			// Bark推送使用简短文本，不支持HTML
			content = "{{value}}，剩余额度：{{value}}，请及时充值"
			values = []interface{}{prompt, common.MailUSD(relayInfo.UserQuota.Dollars())}
		} else if notifyType == dto.NotifyTypeGotify {
			content = "{{value}}，当前剩余额度为 {{value}}，请及时充值。"
			values = []interface{}{prompt, common.MailUSD(relayInfo.UserQuota.Dollars())}
		} else if notifyType == dto.NotifyTypeTelegram {
			content = "当前剩余额度为 {{value}}，请及时充值：{{value}}"
			values = []interface{}{common.MailUSD(relayInfo.UserQuota.Dollars()), link}
		} else {
			content = "{{value}}，当前剩余额度为 {{value}}，为了不影响您的使用，请及时充值。<br/>充值链接：<a href='{{value}}'>{{value}}</a>"
			values = []interface{}{prompt, common.MailUSD(relayInfo.UserQuota.Dollars()), link, link}
		}
		err = NotifyUser(relayInfo.BillingUserID(), userEmail, userSetting, dto.NewNotify(dto.NotifyTypeQuotaExceed, prompt, content, values))
		if err != nil {
			common.SysError(fmt.Sprintf("failed to send quota notify to user %d: %s", relayInfo.BillingUserID(), err.Error()))
		}
	})
}

func quotaNotifyRecipient(info *relaycommon.RelayInfo) (dto.UserSetting, string, error) {
	if info.PayerUserID > 0 && info.PayerUserID != info.UserId {
		payer, err := model.GetUserById(info.PayerUserID, true)
		if err != nil {
			return dto.UserSetting{}, "", err
		}
		return payer.GetSetting(), payer.Email, nil
	}
	return info.UserSetting, info.UserEmail, nil
}
