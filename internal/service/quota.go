func PreWssConsumeQuota(ctx *gin.Context, relayInfo *relaycommon.RelayInfo, usage *dto.RealtimeUsage) error {
	if relayInfo.UsePrice {
		return nil
	}
	if model.GatewayLedgerEnabled() {
		// This usage was already generated by the accepted websocket session.
		// Keep its original reservation and settle the cumulative actual at
		// termination; fresh admission here could discard incurred costs.
		return nil
	}
	userQuota, err := model.GetUserQuota(relayInfo.BillingUserID(), false)
	if err != nil {
		return err
	}

	token, err := model.GetTokenByKey(common.NormalizeAPIKey(relayInfo.TokenKey), false)
	if err != nil {
		return err
	}

	modelName := relayInfo.OriginModelName
	// 确保 UsingGroup 有值（渠道分组）
	if relayInfo.UsingGroup == "" {
		if fg, ok := ctx.Get("final_group"); ok {
			if fgStr, ok2 := fg.(string); ok2 && fgStr != "" {
				relayInfo.UsingGroup = fgStr
			}
		}
	}

	if relayInfo.UsingGroup == "" {
		relayInfo.UsingGroup = model.ChannelLaneDirect
	}
	billingUsage := usagepkg.BillingUsageFromSummary(usagepkg.SummaryFromRealtime(usage))
	quote := QuoteModelUsage(
		relayInfo,
		modelName,
		billingUsage,
		nil,
	)
	quota := QuoteToQuota(quote)
	relayInfo.PriceData.PricingVersion = quote.PricingVersion

	if relayInfo.ProjectID > 0 {
		return consumeProjectRealtimeSegment(ctx, relayInfo, quota)
	}

	if userQuota < quota {
		return fmt.Errorf("user quota is not enough, user quota: %s, need quota: %s", logger.FormatQuota(userQuota), logger.FormatQuota(quota))
	}

	if !token.UnlimitedQuota && token.RemainQuota < quota {
		return fmt.Errorf("token quota is not enough, token remain quota: %s, need quota: %s", logger.FormatQuota(token.RemainQuota), logger.FormatQuota(quota))
	}

	err = postConsumeQuota(relayInfo, quota, 0, false, false)
	if err != nil {
		return err
	}
	logger.LogInfo(ctx, "realtime streaming consume quota success, quota: "+fmt.Sprintf("%d", quota))
	return nil
}

// Each realtime usage event is a separate accepted settlement. Keep its
// request identity in the durable retry payload without changing the session's
// log/resource identity or deduplicating later usage against its first event.
func consumeProjectRealtimeSegment(ctx *gin.Context, info *relaycommon.RelayInfo, quota billing.MicroUSD) error {
	segment := *info
	segment.RequestID = common.GenerateRequestID()
	segment.BudgetSettlementAt = time.Now().UTC()
	segment.FinalPreConsumedQuota = 0
	if err := PreConsumeQuota(ctx, quota, &segment); err != nil {
		return err
	}
	return PostConsumeQuota(&segment, 0, quota, false)
}

func PostWssConsumeQuota(ctx *gin.Context, relayInfo *relaycommon.RelayInfo, modelName string,
	usage *dto.RealtimeUsage, extraContent string) {
	if usage == nil {
		usage = &dto.RealtimeUsage{}
	}

	useTimeSeconds := time.Now().Unix() - relayInfo.StartTime.Unix()
	tokenName := ctx.GetString("token_name")

	perCallPriceUSD := relayInfo.PriceData.PerCallPriceUSD
	usePrice := relayInfo.PriceData.UsePrice

	billingUsage := usagepkg.BillingUsageFromSummary(usagepkg.SummaryFromRealtime(usage))
	quote := QuoteModelUsage(
		relayInfo,
		modelName,
		billingUsage,
		nil,
	)
	quota := QuoteToQuota(quote)
	relayInfo.PriceData.PricingVersion = quote.PricingVersion

	totalTokens := usage.TotalTokens
	var logContent string
	if !usePrice {
		logContent = "按显式模型售卖价计费"
	} else {
		logContent = fmt.Sprintf("按次价格 %.2f", perCallPriceUSD)
	}

	// record all the consume log even if quota is 0
	if totalTokens == 0 && !usePrice {
		// in this case, must be some error happened
		// we cannot just return, because we may have to return the pre-consumed quota
		quota = 0
		quote = billing.QuoteResult{}
		logContent += fmt.Sprintf("（可能是上游超时）")
		logger.LogError(ctx, fmt.Sprintf("total tokens is 0, cannot consume quota, userId %d, channelId %d, "+
			"tokenId %d, model %s， pre-consumed quota %d", relayInfo.BillingUserID(), relayInfo.ChannelId, relayInfo.TokenId, modelName, relayInfo.FinalPreConsumedQuota))
	} else {
		if totalTokens == 0 {
			logContent += fmt.Sprintf("（未返回token，按固定价格计费）")
		}
		if !model.GatewayLedgerEnabled() {
			model.UpdateUserUsedQuota(relayInfo.BillingUserID(), quota)
		}
	}
	logModel := modelName
	if extraContent != "" {
		logContent += ", " + extraContent
	}
	other := GenerateWssOtherInfo(ctx, relayInfo, usage, perCallPriceUSD)
	model.RecordConsumeLog(ctx, relayInfo.ActorID(), model.RecordConsumeLogParams{
		ProjectID: relayInfo.ProjectID, PayerUserID: relayInfo.BillingUserID(),
		ChannelId:        relayInfo.ChannelId,
		PromptTokens:     usage.InputTokens,
		CompletionTokens: usage.OutputTokens,
		ModelName:        logModel,
		TokenName:        tokenName,
		AmountMicrousd:   quote.TotalMicrousd,
		PricingVersion:   quote.PricingVersion,
		LineItems:        QuoteLineItemsJSON(quote),
		Content:          logContent,
		TokenId:          relayInfo.TokenId,
		UseTimeSeconds:   int(useTimeSeconds),
		IsStream:         relayInfo.IsStream,
		Group:            relayInfo.UsingGroup,
		Other:            other,
		UsageFact:        usagepkg.FactFromRealtimeUsage(usage, other, UsageProviderFamilyForRelay(relayInfo)),
	})
	if model.GatewayLedgerEnabled() {
		if err := SettleRedisLedgerWithFacts(ctx, relayInfo, quota); err != nil {
			logger.LogError(ctx, "error settling realtime session: "+err.Error())
		}
	}
}

func PostClaudeConsumeQuota(ctx *gin.Context, relayInfo *relaycommon.RelayInfo, usage *dto.Usage) {

	usageSummary := usagepkg.SummaryFromDTO(usage)
	useTimeSeconds := time.Now().Unix() - relayInfo.StartTime.Unix()
	promptTokens := usageSummary.PromptTokens
	originalPromptTokens := promptTokens
	completionTokens := usageSummary.CompletionTokens
	modelName := relayInfo.OriginModelName

	tokenName := ctx.GetString("token_name")
	perCallPriceUSD := relayInfo.PriceData.PerCallPriceUSD
	cacheTokens := usageSummary.CacheReadTokens
	cacheCreationTokens := usageSummary.CacheWriteTokens
	cacheCreation5mTokens := usageSummary.CacheWrite5mTokens
	cacheCreation1hTokens := usageSummary.CacheWrite1hTokens

	billingUsage := buildClaudeBillingUsage(relayInfo.PriceData.UsePrice, usageSummary)
	quote := QuoteModelUsage(relayInfo, modelName, billingUsage, nil)
	quota := QuoteToQuota(quote)
	relayInfo.PriceData.PricingVersion = quote.PricingVersion

	totalTokens := promptTokens + completionTokens

	var logContent string
	// record all the consume log even if quota is 0
	if totalTokens == 0 && !relayInfo.PriceData.UsePrice {
		// in this case, must be some error happened
		// we cannot just return, because we may have to return the pre-consumed quota
		quota = 0
		quote = billing.QuoteResult{}
		logContent += fmt.Sprintf("（可能是上游出错）")
		logger.LogError(ctx, fmt.Sprintf("total tokens is 0, cannot consume quota, userId %d, channelId %d, "+
			"tokenId %d, model %s， pre-consumed quota %d", relayInfo.BillingUserID(), relayInfo.ChannelId, relayInfo.TokenId, modelName, relayInfo.FinalPreConsumedQuota))
	} else {
		if totalTokens == 0 {
			logContent += fmt.Sprintf("（未返回token，按固定价格计费）")
		}
		model.UpdateUserUsedQuota(relayInfo.BillingUserID(), quota)
	}

	quotaDelta := quota - relayInfo.FinalPreConsumedQuota

	if quotaDelta > 0 {
		logger.LogInfo(ctx, fmt.Sprintf("Additional quota charged after pre-charge: %s (actual cost: %s, pre-charged: %s)",
			logger.FormatQuota(quotaDelta),
			logger.FormatQuota(quota),
			logger.FormatQuota(relayInfo.FinalPreConsumedQuota),
		))
	} else if quotaDelta < 0 {
		logger.LogInfo(ctx, fmt.Sprintf("Excess pre-charged quota refunded: %s (actual cost: %s, pre-charged: %s)",
			logger.FormatQuota(-quotaDelta),
			logger.FormatQuota(quota),
			logger.FormatQuota(relayInfo.FinalPreConsumedQuota),
		))
	}

	if !model.GatewayLedgerEnabled() {
		if err := PostConsumeQuota(relayInfo, quotaDelta, relayInfo.FinalPreConsumedQuota, true); err != nil {
			logger.LogError(ctx, "error consuming token remain quota: "+err.Error())
		}
	}

	other := GenerateClaudeOtherInfo(ctx, relayInfo, cacheTokens, cacheCreationTokens,
		cacheCreation5mTokens, cacheCreation1hTokens, perCallPriceUSD)
	model.RecordConsumeLog(ctx, relayInfo.ActorID(), model.RecordConsumeLogParams{
		ProjectID: relayInfo.ProjectID, PayerUserID: relayInfo.BillingUserID(),
		ChannelId:        relayInfo.ChannelId,
		PromptTokens:     originalPromptTokens,
		CompletionTokens: completionTokens,
		ModelName:        modelName,
		TokenName:        tokenName,
		AmountMicrousd:   quote.TotalMicrousd,
		PricingVersion:   quote.PricingVersion,
		LineItems:        QuoteLineItemsJSON(quote),
		Content:          logContent,
		TokenId:          relayInfo.TokenId,
		UseTimeSeconds:   int(useTimeSeconds),
		IsStream:         relayInfo.IsStream,
		Group:            relayInfo.UsingGroup,
		Other:            other,
		UsageFact:        usagepkg.FactFromProviderUsage(usage, other, UsageProviderFamilyForRelay(relayInfo)),
	})
	if model.GatewayLedgerEnabled() {
		if err := SettleRedisLedgerWithFacts(ctx, relayInfo, quota); err != nil {
			logger.LogError(ctx, "error settling Claude usage: "+err.Error())
		}
	}

}

func buildClaudeBillingUsage(usePrice bool, usageSummary usagepkg.Summary) billing.Usage {
	if usePrice {
		return billing.Usage{RequestCount: 1}
	}
	return usagepkg.BillingUsageFromSummary(usageSummary)
}

