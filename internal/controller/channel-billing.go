// GetAuthHeader get auth header
func GetAuthHeader(token string) http.Header {
	h := http.Header{}
	h.Add("Authorization", fmt.Sprintf("Bearer %s", token))
	return h
}

// GetClaudeAuthHeader get claude auth header
func GetClaudeAuthHeader(token string) http.Header {
	h := http.Header{}
	h.Add("x-api-key", token)
	h.Add("anthropic-version", "2023-06-01")
	return h
}

// upstreamStatusError is a provider answering an operator lookup (balance,
// model list) with a non-200 status.
type upstreamStatusError struct {
	status int
}

func (e *upstreamStatusError) Error() string {
	return fmt.Sprintf("status code: %d", e.status)
}

// errBalanceUnsupported marks a channel type without a balance contract.
var errBalanceUnsupported = types.Err(types.ErrorCodeChannelBalanceUnsupported, types.D{"reason": "channel_type"})

// upstreamFailure turns a failed provider lookup into its catalog error. The
// status is the provider's HTTP status, or 0 when no answer arrived; the
// cause (which may carry the URL) is logged, never sent.
func upstreamFailure(err error, code types.ErrorCode) error {
	if types.ErrCode(err) != "" {
		return err
	}
	status := 0
	var statusErr *upstreamStatusError
	if errors.As(err, &statusErr) {
		status = statusErr.status
	}
	return types.WrapErr(err, code, types.D{"status": status})
}

func GetResponseBody(method, url string, channel *model.Channel, headers http.Header) ([]byte, error) {
	req, err := http.NewRequest(method, url, nil)
	if err != nil {
		return nil, err
	}
	for k := range headers {
		req.Header.Add(k, headers.Get(k))
	}
	client, err := service.NewProxyHttpClient(channel.GetSetting().Proxy)
	if err != nil {
		return nil, err
	}
	res, err := client.Do(req)
	if err != nil {
		return nil, err
	}
	if res.StatusCode != http.StatusOK {
		_ = res.Body.Close()
		return nil, &upstreamStatusError{status: res.StatusCode}
	}
	body, err := io.ReadAll(res.Body)
	if err != nil {
		return nil, err
	}
	err = res.Body.Close()
	if err != nil {
		return nil, err
	}
	return body, nil
}

func updateChannelCloseAIBalance(channel *model.Channel) (float64, error) {
	url := fmt.Sprintf("%s/dashboard/billing/credit_grants", channel.GetBaseURL())
	body, err := GetResponseBody("GET", url, channel, GetAuthHeader(channel.Key))

	if err != nil {
		return 0, err
	}
	response := OpenAICreditGrants{}
	err = json.Unmarshal(body, &response)
	if err != nil {
		return 0, err
	}
	return response.TotalAvailable, nil
}

func updateChannelOpenAISBBalance(channel *model.Channel) (float64, error) {
	url := fmt.Sprintf("https://api.openai-sb.com/sb-api/user/status?api_key=%s", channel.Key)
	body, err := GetResponseBody("GET", url, channel, GetAuthHeader(channel.Key))
	if err != nil {
		return 0, err
	}
	response := OpenAISBUsageResponse{}
	err = json.Unmarshal(body, &response)
	if err != nil {
		return 0, err
	}
	if response.Data == nil {
		return 0, errors.New(response.Msg)
	}
	balance, err := strconv.ParseFloat(response.Data.Credit, 64)
	if err != nil {
		return 0, err
	}
	return balance, nil
}

func updateChannelBalance(channel *model.Channel) (float64, error) {
	baseURL := constant.ChannelBaseURLs[channel.Type]
	if channel.GetBaseURL() == "" {
		channel.BaseURL = &baseURL
	}
	switch channel.Type {
	case constant.ChannelTypeOpenAI:
		if channel.GetBaseURL() != "" {
			baseURL = channel.GetBaseURL()
		}
	case constant.ChannelTypeCustom:
		baseURL = channel.GetBaseURL()
	default:
		return 0, errBalanceUnsupported
	}
	url := fmt.Sprintf("%s/v1/dashboard/billing/subscription", baseURL)

	body, err := GetResponseBody("GET", url, channel, GetAuthHeader(channel.Key))
	if err != nil {
		return 0, err
	}
	subscription := OpenAISubscriptionResponse{}
	err = json.Unmarshal(body, &subscription)
	if err != nil {
		return 0, err
	}
	now := time.Now()
	startDate := fmt.Sprintf("%s-01", now.Format("2006-01"))
	endDate := now.Format("2006-01-02")
	if !subscription.HasPaymentMethod {
		startDate = now.AddDate(0, 0, -100).Format("2006-01-02")
	}
	url = fmt.Sprintf("%s/v1/dashboard/billing/usage?start_date=%s&end_date=%s", baseURL, startDate, endDate)
	body, err = GetResponseBody("GET", url, channel, GetAuthHeader(channel.Key))
	if err != nil {
		return 0, err
	}
	usage := OpenAIUsageResponse{}
	err = json.Unmarshal(body, &usage)
	if err != nil {
		return 0, err
	}
	balance := subscription.HardLimitUSD - usage.TotalUsage/100
	return balance, nil
}

func UpdateChannelBalance(c *gin.Context) {
	id, err := resolveChannelID(c.Param("id"))
	if err != nil {
		httperr.Write(c, err)
		return
	}
	channel, err := model.CacheGetChannel(id)
	if err != nil {
		httperr.Write(c, err)
		return
	}
	if constant.IsSearchChannelType(channel.Type) {
		rejectSearchBackendChannelMutation(c, "edit")
		return
	}
	if channel.ChannelInfo.IsMultiKey {
		httperr.Code(c, types.ErrorCodeChannelBalanceUnsupported, types.D{"reason": "multi_key"})
		return
	}
	balance, err := updateChannelBalance(channel)
	if err != nil {
		httperr.Write(c, upstreamFailure(err, types.ErrorCodeChannelBalanceQueryFailed))
		return
	}
	common.ApiSuccess(c, gin.H{"balance": balance})
}

func updateAllChannelsBalance() error {
	channels, err := model.GetAllChannels(0, 0, true, false)
	if err != nil {
		return err
	}
	for _, channel := range channels {
		if channel.Status != common.ChannelStatusEnabled {
			continue
		}
		if constant.IsSearchChannelType(channel.Type) {
			continue
		}
		if channel.ChannelInfo.IsMultiKey {
			continue // skip multi-key channels
		}
		// Only providers exposing the OpenAI-compatible billing contract can be
		// refreshed here. updateChannelBalance returns an error for all other
		// channel types, including Azure-style cloud channels, and the batch
		// refresh intentionally leaves their stored balance unchanged.
		balance, err := updateChannelBalance(channel)
		if err != nil {
			continue
		} else {
			// err is nil & balance <= 0 means quota is used up
			if balance <= 0 {
				service.DisableChannel(*types.NewChannelError(channel.Id, channel.Type, channel.Name, channel.ChannelInfo.IsMultiKey, "", channel.GetAutoBan()), "余额不足")
			}
		}
		time.Sleep(common.RequestInterval)
	}
	return nil
}

// RunChannelBalanceUpdateOnce performs one synchronous balance refresh. It is
// used by external schedulers that own the cadence and process lifecycle.
func RunChannelBalanceUpdateOnce() error {
	return updateAllChannelsBalance()
}

func UpdateAllChannelsBalance(c *gin.Context) {
	// Keep this root-only manual action synchronous so the response confirms the
	// refresh has finished. Scheduled refreshes run outside the request lifecycle
	// through RunChannelBalanceUpdateOnce/AutomaticallyUpdateChannels.
	err := updateAllChannelsBalance()
	if err != nil {
		httperr.Write(c, err)
		return
	}
	c.JSON(http.StatusOK, gin.H{
		"success": true,
		"message": "",
	})
	return
}

func AutomaticallyUpdateChannels(frequency int) {
	for {
		time.Sleep(time.Duration(frequency) * time.Minute)
		common.SysLog("updating all channels")
		_ = updateAllChannelsBalance()
		common.SysLog("channels update done")
	}
}
