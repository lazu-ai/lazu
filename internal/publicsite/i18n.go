// Locales the public site publishes. English is unprefixed; the others live
// under /zh, /zh-TW and /ja, matching the prerendered marketing pages.
var Locales = []string{"en", "zh", "zh-TW", "ja"}

// NormalizeLocale maps a URL prefix to a published locale ("" -> en).
func NormalizeLocale(value string) string {
	for _, locale := range Locales {
		if strings.EqualFold(value, locale) {
			return locale
		}
	}
	return "en"
}

// LocalizedPath prefixes a bare path ("/models/x") with the locale.
func LocalizedPath(bare, locale string) string {
	if bare == "" {
		bare = "/"
	}
	if locale == "en" || locale == "" {
		return bare
	}
	if bare == "/" {
		return "/" + locale + "/"
	}
	return "/" + locale + bare
}

// HTMLLang is the <html lang> value for a locale.
func HTMLLang(locale string) string {
	switch locale {
	case "zh":
		return "zh-CN"
	case "zh-TW":
		return "zh-TW"
	case "ja":
		return "ja"
	}
	return "en"
}

// OGLocale is the og:locale value for a locale.
func OGLocale(locale string) string {
	switch locale {
	case "zh":
		return "zh_CN"
	case "zh-TW":
		return "zh_TW"
	case "ja":
		return "ja_JP"
	}
	return "en_US"
}

