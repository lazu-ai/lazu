// T formats the message id for a locale, falling back to English.
func T(locale, id string, args ...any) string {
	message, ok := messages[locale][id]
	if !ok {
		message, ok = messages["en"][id]
	}
	if !ok {
		return id
	}
	if len(args) == 0 {
		return message
	}
	return fmt.Sprintf(message, args...)
}

// Join lists words the way the locale does ("a, b and c" / "a、b、c").
func Join(locale string, items []string) string {
	switch len(items) {
	case 0:
		return ""
	case 1:
		return items[0]
	}
	comma := T(locale, "joinComma")
	and := T(locale, "joinAnd")
	return strings.Join(items[:len(items)-1], comma) + and + items[len(items)-1]
}
