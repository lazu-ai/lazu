export function createSidebars() {
  return {
    "/": createSidebar("", sidebarCopy.en),
    "/zh/": createSidebar("/zh", sidebarCopy.zh),
    "/zh-TW/": createSidebar("/zh-TW", sidebarCopy["zh-TW"]),
    "/ja/": createSidebar("/ja", sidebarCopy.ja),
  };
}
