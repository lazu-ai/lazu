func familyOf(id string) string {
	digits := strings.TrimPrefix(id, "LZ-")
	if strings.HasPrefix(digits, "2") {
		return digits[:2]
	}
	return digits[:1]
}

var familyOrder = []string{"1", "20", "21", "22", "23", "26", "3", "4", "5", "6", "7", "9"}

func loadCopy(root, lang string) (map[string]string, error) {
	files, err := filepath.Glob(filepath.Join(root, "apps/web/src/i18n/locales/errors", lang, "*.json"))
	if err != nil {
		return nil, err
	}
	copyByCode := map[string]string{}
	for _, file := range files {
		raw, err := os.ReadFile(file)
		if err != nil {
			return nil, err
		}
		var entries map[string]any
		if err := json.Unmarshal(raw, &entries); err != nil {
			return nil, fmt.Errorf("%s: %w", file, err)
		}
		for key, value := range entries {
			if text, ok := value.(string); ok {
				copyByCode[key] = text
			}
		}
	}
	return copyByCode, nil
}

func cell(text string) string {
	text = strings.ReplaceAll(text, "|", "\\|")
	text = strings.ReplaceAll(text, "{", "\\{")
	return strings.ReplaceAll(text, "}", "\\}")
}

func render(l locale, copyByCode map[string]string) (string, error) {
	byFamily := map[string][]types.ErrorCode{}
	for _, code := range types.PublicCatalogCodes() {
		spec := types.Catalog[code]
		byFamily[familyOf(spec.ID)] = append(byFamily[familyOf(spec.ID)], code)
	}
	var b bytes.Buffer
	b.WriteString(startMarker + "\n")
	for _, family := range familyOrder {
		codes := byFamily[family]
		if len(codes) == 0 {
			continue
		}
		sort.Slice(codes, func(i, j int) bool { return types.Catalog[codes[i]].ID < types.Catalog[codes[j]].ID })
		fmt.Fprintf(&b, "\n### %s\n\n", l.headings[family])
		fmt.Fprintf(&b, "| %s | %s | %s | %s | %s |\n| --- | --- | --- | --- | --- |\n",
			l.columns[0], l.columns[1], l.columns[2], l.columns[3], l.columns[4])
		for _, code := range codes {
			w := types.RenderWire(code, nil, 0)
			meaning, ok := copyByCode[string(code)]
			if !ok {
				return "", fmt.Errorf("%s: no %s copy for %s", l.page, l.lang, code)
			}
			fmt.Fprintf(&b, "| <a id=\"%s\"></a>`%s` | `%s` | %d | `%s` | %s |\n",
				strings.ToLower(w.ID), w.ID, code, w.Status, w.Type, cell(meaning))
		}
	}
	b.WriteString("\n" + endMarker)
	return b.String(), nil
}

func main() {
	check := flag.Bool("check", false, "exit 1 when a page is out of date instead of writing it")
	flag.Parse()
	root, err := os.Getwd()
	if err != nil {
		fail(err)
	}
	stale := false
	for _, l := range locales {
		copyByCode, err := loadCopy(root, l.lang)
		if err != nil {
			fail(err)
		}
		block, err := render(l, copyByCode)
		if err != nil {
			fail(err)
		}
		path := filepath.Join(root, l.page)
		raw, err := os.ReadFile(path)
		if err != nil {
			fail(err)
		}
		page := string(raw)
		start := strings.Index(page, startMarker)
		end := strings.Index(page, endMarker)
		if start < 0 || end < start {
			fail(fmt.Errorf("%s: reference markers missing", l.page))
		}
		updated := page[:start] + block + page[end+len(endMarker):]
		if updated == page {
			continue
		}
		if *check {
			fmt.Fprintf(os.Stderr, "%s is out of date; run go run ./ops/tools/errdocs\n", l.page)
			stale = true
			continue
		}
		if err := os.WriteFile(path, []byte(updated), 0o644); err != nil {
			fail(err)
		}
		fmt.Println("wrote", l.page)
	}
	if stale {
		os.Exit(1)
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "errdocs:", err)
	os.Exit(1)
}
