// page in every language, from the error catalog and the console's error
// copy. The block between the reference markers is generated; everything
// else on the page is hand-written.
//
//	go run ./ops/tools/errdocs          # rewrite the pages
//	go run ./ops/tools/errdocs -check   # exit 1 if a page is stale (CI)
